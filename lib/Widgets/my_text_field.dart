  static const _wordPattern = r"[A-Za-z]+(?:['’][A-Za-z]+)*";
  static const _bitCount = 250007;
  static const _hashCount = 10;
  static final _dictionary = base64Decode(_encodedDictionary);

  @override
  Future<List<SuggestionSpan>?> fetchSpellCheckSuggestions(
    Locale locale,
    String text,
  ) async {
    if (locale.languageCode.toLowerCase() != 'en' || text.trim().isEmpty) {
      return const <SuggestionSpan>[];
    }

    final suggestions = <SuggestionSpan>[];
    for (final match in RegExp(_wordPattern).allMatches(text)) {
      final originalWord = match.group(0)!;
      final word = originalWord.toLowerCase().replaceAll('’', "'");

      if (_isPartOfUrlEmailOrCode(text, match.start, match.end) ||
          (originalWord.length > 1 &&
              originalWord == originalWord.toUpperCase()) ||
          _isKnownWord(word)) {
        continue;
      }

      suggestions.add(
        SuggestionSpan(
          TextRange(start: match.start, end: match.end),
          const <String>[],
        ),
      );
    }
    return suggestions;
  }

  static bool _isKnownWord(String word) {
    if (word.length <= 1 || _dictionaryContains(word)) return true;
    if (word.endsWith("'s")) {
      return _dictionaryContains(word.substring(0, word.length - 2));
    }
    return false;
  }

  static bool _dictionaryContains(String word) {
    var firstHash = 0;
    var secondHash = 5381;
    for (final codeUnit in word.codeUnits) {
      firstHash = (firstHash * 31 + codeUnit) & 0x7fffffff;
      secondHash = (secondHash * 37 + codeUnit) & 0x7fffffff;
    }
    secondHash |= 1;

    for (var index = 0; index < _hashCount; index++) {
      final bit = (firstHash + index * secondHash + index * index) % _bitCount;
      if ((_dictionary[bit >> 3] & (1 << (bit & 7))) == 0) return false;
    }
    return true;
  }

  static bool _isPartOfUrlEmailOrCode(String text, int start, int end) {
    bool isJoiningCharacter(int codeUnit) =>
        (codeUnit >= 48 && codeUnit <= 57) ||
        codeUnit == 46 ||
        codeUnit == 47 ||
        codeUnit == 64 ||
        codeUnit == 92 ||
        codeUnit == 95;

    return (start > 0 && isJoiningCharacter(text.codeUnitAt(start - 1))) ||
        (end < text.length && isJoiningCharacter(text.codeUnitAt(end)));
  }

