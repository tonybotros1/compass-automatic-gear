typedef _SpellCheckFieldBuilder = Widget Function(
  SpellCheckConfiguration configuration,
);

class _FocusedSpellCheck extends StatefulWidget {
  const _FocusedSpellCheck({required this.enabled, required this.builder});

  final bool enabled;
  final _SpellCheckFieldBuilder builder;

  @override
  State<_FocusedSpellCheck> createState() => _FocusedSpellCheckState();
}

class _FocusedSpellCheckState extends State<_FocusedSpellCheck> {
  final _fieldKey = GlobalKey();
  _FocusAwareSpellCheckService? _service;
  bool _hasFocus = false;
  int _focusGeneration = 0;

  @override
  void initState() {
    super.initState();
    _configureService();
  }

  @override
  void didUpdateWidget(_FocusedSpellCheck oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (widget.enabled != oldWidget.enabled) _configureService();
  }

  void _configureService() {
    final nativeSpellCheckAvailable = WidgetsBinding
        .instance
        .platformDispatcher
        .nativeSpellCheckServiceDefined;
    final SpellCheckService? baseService = kIsWeb
        ? _browserEnglishSpellChecker
        : nativeSpellCheckAvailable
        ? DefaultSpellCheckService()
        : null;
    _service = widget.enabled && baseService != null
        ? _FocusAwareSpellCheckService(baseService)
        : null;
    _service?.focused = _hasFocus;
  }

  void _handleFocusChange(bool hasFocus) {
    _hasFocus = hasFocus;
    _service?.focused = hasFocus;
    final generation = ++_focusGeneration;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted && generation == _focusGeneration) {
        _updateUnderline(hasFocus, generation);
      }
    });
  }

  Future<void> _updateUnderline(bool show, int generation) async {
    final editable = _findEditableTextState();
    if (editable == null) return;

    if (!show) {
      editable.spellCheckResults = null;
      editable.renderEditable.text = editable.buildTextSpan();
      return;
    }

    final service = _service;
    final text = editable.textEditingValue.text;
    if (service == null || text.isEmpty) return;

    final results = await service.fetchSpellCheckSuggestions(
      Localizations.maybeLocaleOf(context) ?? const Locale('en'),
      text,
    );
    if (!mounted ||
        !_hasFocus ||
        generation != _focusGeneration ||
        editable.textEditingValue.text != text) {
      return;
    }

    editable.spellCheckResults = SpellCheckResults(
      text,
      results ?? const <SuggestionSpan>[],
    );
    editable.renderEditable.text = editable.buildTextSpan();
  }

  EditableTextState? _findEditableTextState() {
    final fieldContext = _fieldKey.currentContext;
    if (fieldContext == null) return null;

    EditableTextState? result;
    void visit(Element element) {
      if (result != null) return;
      if (element is StatefulElement && element.state is EditableTextState) {
        result = element.state as EditableTextState;
        return;
      }
      element.visitChildElements(visit);
    }

    (fieldContext as Element).visitChildElements(visit);
    return result;
  }

  @override
  Widget build(BuildContext context) {
    final service = _service;
    final configuration = service == null
        ? const SpellCheckConfiguration.disabled()
        : SpellCheckConfiguration(
            spellCheckService: service,
            misspelledTextStyle: const TextStyle(
              decoration: TextDecoration.underline,
              decorationColor: Colors.red,
              decorationStyle: TextDecorationStyle.wavy,
            ),
          );

    return Focus(
      canRequestFocus: false,
      skipTraversal: true,
      onFocusChange: _handleFocusChange,
      child: KeyedSubtree(
        key: _fieldKey,
        child: widget.builder(configuration),
      ),
    );
  }
}

class _FocusAwareSpellCheckService implements SpellCheckService {
  _FocusAwareSpellCheckService(this._service);

  final SpellCheckService _service;
  bool isFocused = false;
  int _focusGeneration = 0;

  @override
  Future<List<SuggestionSpan>?> fetchSpellCheckSuggestions(
    Locale locale,
    String text,
  ) async {
    if (!isFocused) return const <SuggestionSpan>[];
    final generation = _focusGeneration;
    final results = await _service.fetchSpellCheckSuggestions(locale, text);
    if (!isFocused || generation != _focusGeneration) {
      return const <SuggestionSpan>[];
    }
    return results;
  }

  set focused(bool value) {
    if (isFocused == value) return;
    isFocused = value;
    _focusGeneration++;
  }
}

Widget myTextFormFieldWithBorder({
  String? labelText,
  String? hintText,
  TextEditingController? controller,
  bool? validate,
  bool obscureText = false,
  Widget? suffixIcon,
  Icon? icon,
  bool? isnumber,
  bool? isDouble,
  bool? isDate,
  double? width,
  String? initialValue,
  bool? isCapitaLetters,
  FocusNode? focusNode,
  FocusNode? nextFocusNode,
  bool? moneyFormat,
  TextInputAction? textInputAction,
  void Function()? onEditingComplete,
  maxLines = 1,
  TextAlign? textAlign = TextAlign.start,
  int? minLines,
  TextInputType? keyboardType,
  void Function(String)? onChanged,
  void Function(String)? onFieldSubmitted,
  bool? isEnabled = true,
  void Function(PointerDownEvent)? onTapOutside,
  bool? readOnly,
  FocusNode? previousFocusNode,
}) {
  return SizedBox(
    width: width,
    child: Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        labelText != null
            ? Padding(
                padding: const EdgeInsets.only(left: 2),
                child: Text(
                  overflow: TextOverflow.ellipsis,
                  labelText,
                  style: textFieldLabelStyle,
                ),
              )
            : const SizedBox(),
        Focus(
          canRequestFocus: false,
          skipTraversal: true,
          onKeyEvent: (node, event) {
            if (event is! KeyDownEvent) return KeyEventResult.ignored;
            if (event.logicalKey != LogicalKeyboardKey.tab) {
              return KeyEventResult.ignored;
            }

            final isShift = HardwareKeyboard.instance.isShiftPressed;

            if (isShift) {
              if (previousFocusNode != null) {
                previousFocusNode.requestFocus();
                return KeyEventResult.handled;
              }
              return KeyEventResult.ignored; // default back traversal
            } else {
              if (nextFocusNode != null) {
                nextFocusNode.requestFocus();
                return KeyEventResult.handled;
              }
              return KeyEventResult.ignored; // default forward traversal
            }
          },
          child: _FocusedSpellCheck(
            enabled:
                !obscureText &&
                isnumber != true &&
                isDouble != true &&
                isDate != true &&
                moneyFormat != true &&
                keyboardType != TextInputType.emailAddress &&
                keyboardType != TextInputType.url &&
                keyboardType != TextInputType.phone,
            builder: (spellCheckConfiguration) => TextFormField(
              spellCheckConfiguration: spellCheckConfiguration,
              initialValue: initialValue,
              canRequestFocus: true,
              readOnly: readOnly ?? false,
              onTapOutside: onTapOutside,
              onEditingComplete: onEditingComplete,
              textInputAction: textInputAction,
              focusNode: focusNode,
              onFieldSubmitted: (v) {
                if (nextFocusNode != null) {
                  nextFocusNode.requestFocus();
                }
                onFieldSubmitted?.call(v);
              },
              textAlign: textAlign!,
              style: textFieldFontStyle,
              minLines: minLines,
              maxLines: maxLines,
              onChanged: onChanged,
              inputFormatters: isnumber == true
                  ? [FilteringTextInputFormatter.digitsOnly]
                  : isDouble == true
                  ? [DecimalTextInputFormatter()]
                  : isDate == true
                  ? [DateTextFormatter()]
                  : isCapitaLetters == true
                  ? [CapitalLettersOnlyFormatter()]
                  : moneyFormat == true
                  ? [CurrencyInputFormatter()]
                  : null,
              enabled: isEnabled,
              obscureText: obscureText,
              keyboardType: keyboardType,
              controller: controller,
              decoration: InputDecoration(
                contentPadding: const EdgeInsets.symmetric(
                  horizontal: 10,
                  vertical: !kIsWeb ? 7 : 11,
                ),
                isDense: true,
                icon: icon,
                suffixIcon: ExcludeFocus(child: suffixIcon ?? const SizedBox()),
                suffixIconConstraints: const BoxConstraints(
                  maxHeight: 30,
                  maxWidth: 40,
                ),
                prefixIconConstraints: const BoxConstraints(
                  maxHeight: 15,
                  maxWidth: 15,
                ),
                hintStyle: const TextStyle(color: Colors.grey, fontSize: 14),
                // labelText: labelText,
                alignLabelWithHint: true,

                hintText: hintText,
                labelStyle: TextStyle(
                  color: isEnabled == false
                      ? Colors.grey.shade500
                      : Colors.grey.shade700,
                ),
                fillColor: isEnabled == true
                    ? Colors.white
                    : Colors.grey.shade200,
                filled: true,
                // focusedBorder: const OutlineInputBorder(
                //   // borderRadius: BorderRadius.circular(borderRadius!),
                //   borderSide: BorderSide(color: Colors.grey, width: 2.0),
                // ),
                enabledBorder: const OutlineInputBorder(
                  // borderRadius: BorderRadius.circular(borderRadius),
                  borderSide: BorderSide(color: Colors.grey, width: 1.0),
                ),
                disabledBorder: OutlineInputBorder(
                  // borderRadius: BorderRadius.circular(borderRadius),
                  borderSide: BorderSide(color: Colors.grey.shade400, width: 1.0),
                ),
                errorBorder: const OutlineInputBorder(
                  // borderRadius: BorderRadius.circular(5),
                  borderSide: BorderSide(color: Colors.red, width: 1.0),
                ),
                focusedErrorBorder: const OutlineInputBorder(
                  // borderRadius: BorderRadius.circular(5),
                  borderSide: BorderSide(color: Colors.red, width: 2.0),
                ),
              ),
              validator: validate != false
                  ? (value) {
                      if (value!.isEmpty) {
                        return 'Please Enter $labelText';
                      }
                      return null;
                    }
                  : null,
            ),
          ),
        ),
      ],
    ),
  );
}


